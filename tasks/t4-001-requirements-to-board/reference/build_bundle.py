"""Build the synthetic t4-001 reference bundle.

Synthetic: this bundle is assembled from AEDL's own reference designs and
AEDL's own evaluators, not produced by a design tool. See README.md beside
this file. It exists so the evaluator has a known-good bundle to pass; a
bundle generated by an agent workflow will replace it.

- architecture: the t3-001 reference design (output of
  tasks/t3-001-satcom-terminal-28ghz/reference/solve.py, copied here because
  that search takes about four minutes);
- element spec: tasks/t1-001-patch-28ghz-ro4350b/reference/design.yaml;
- board: antenna-cad's KiCad emitter run on that element spec;
- verdicts: the evaluator's own recomputation, each number tagged with the
  SHA-256 of the artifact it was computed from.

Usage: python build_bundle.py [output_dir]
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "src"))

TASK_DIR = Path(__file__).resolve().parents[1]
TASKS = TASK_DIR.parent
ELEMENT_REFERENCE = TASKS / "t1-001-patch-28ghz-ro4350b" / "reference" / "design.yaml"

#: t3-001 reference/solve.py output (2026-10-11, phased-array-systems 0.10.1).
ARCHITECTURE: dict[str, Any] = {
    "array": {
        "nx": 16,
        "ny": 16,
        "dx_lambda": 0.5,
        "dy_lambda": 0.5,
        "taper_type": "taylor",
        "taper_sll_db": -34.0,
        "phase_bits": 4,
    },
    "rf": {"tx_power_w_per_elem": 0.1903, "pa_class": "A"},
    "digital": {
        "digitization_level": "subarray",
        "adc_enob": 10.0,
        "subarray_nx": 8,
        "subarray_ny": 8,
    },
}

ELEMENT_REL = "element/design.yaml"
BOARD_REL = "board/patch.kicad_pcb"


def _sha256(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def build(out_dir: Path) -> dict[str, Any]:
    from antenna_cad.backends.kicad import write_kicad_project
    from antenna_cad.designspec import DesignSpec

    from aedl.evaluators.requirements_bundle import recompute
    from aedl.spec import find_task

    spec = find_task(TASKS, "t4-001")
    (out_dir / "element").mkdir(parents=True, exist_ok=True)
    (out_dir / "board").mkdir(parents=True, exist_ok=True)

    element_bytes = ELEMENT_REFERENCE.read_bytes()
    (out_dir / ELEMENT_REL).write_bytes(element_bytes)

    design = DesignSpec.load(out_dir / ELEMENT_REL).synthesize()
    with tempfile.TemporaryDirectory() as td:
        write_kicad_project(design, td)
        (board,) = Path(td).glob("*.kicad_pcb")
        shutil.copyfile(board, out_dir / BOARD_REL)

    bundle: dict[str, Any] = {
        "schema": "aedl.t4-001.bundle/1",
        "architecture": ARCHITECTURE,
        "element_spec": ELEMENT_REL,
        "board": BOARD_REL,
        "verdicts": {},
    }
    architecture_hash = _sha256(json.dumps(ARCHITECTURE, sort_keys=True).encode())
    element_hash = _sha256(element_bytes)
    for rid, rec in sorted(recompute(spec, out_dir, bundle).items()):
        is_element = rec.source.startswith("task:")
        bundle["verdicts"][rid] = {
            "status": rec.status,
            "actual": round(rec.actual, 6),
            "unit": rec.unit,
            "provenance": {
                "artifact_hash": element_hash if is_element else architecture_hash,
                "capability": "aedl.evaluators.patch_element"
                if is_element
                else "aedl.evaluators.satcom_terminal",
                "origin": "derived",
                "fidelity": "analytic",
            },
        }
    (out_dir / "bundle.json").write_text(json.dumps(bundle, indent=2) + "\n")
    return bundle


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else TASK_DIR / "reference" / "submission"
    result = build(out)
    passes = sum(v["status"] == "pass" for v in result["verdicts"].values())
    print(f"wrote {out / 'bundle.json'}: {passes}/{len(result['verdicts'])} requirements pass")
